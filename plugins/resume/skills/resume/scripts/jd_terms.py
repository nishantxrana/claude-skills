#!/usr/bin/env python3
"""jd_terms.py - pull searchable terms out of a job description and compare with the resume.

  python jd_terms.py jd.txt [--resume resume.txt] [--out keywords.txt]

Prints, ranked: known tech terms (references/tech-terms.txt) with how often the JD uses them and
whether they sit under a must-have heading; capitalised phrases the vocabulary does not know
(review by hand); hard requirements (years, degree, location, work type, notice period).
--out writes a keywords file for resume_check.py --keywords (canonical|aliases per line).
This is a starting point: Claude and the user decide which terms are true for the resume.
"""
from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path

VOCAB = Path(__file__).resolve().parent.parent / "references" / "tech-terms.txt"
MUST_HEAD = re.compile(r"^(must|required|requirements|mandatory|minimum|basic qualifications|what you.ll need|"
                       r"you have|qualifications|key skills|skills required)", re.I)
NICE_HEAD = re.compile(r"^(nice|good to have|preferred|bonus|plus|desired|additional)", re.I)
STOP = set("""The And For With Our You Your We Are Will This That From Have Has Job Role Team Teams Work Working
About Who What Why How Key Good Strong Experience Knowledge Ability Skills Responsibilities Requirements
Qualifications Preferred Must Nice Benefits Company Location Apply Equal Opportunity Employer Candidate
Candidates Year Years Including Within Across Ensure Using Use Build Design Develop Manage Support""".split())


def load_vocab():
    out = []
    for l in VOCAB.read_text(encoding="utf-8").splitlines():
        l = l.strip()
        if l and not l.startswith("#"):
            names = [x.strip() for x in l.split("|") if x.strip()]
            out.append(names)
    return out


def pattern(alias):
    return re.compile(r"(?<![\w.+#/-])" + re.escape(alias) + r"(?![\w+#-])", re.I if len(alias) > 3 else 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("jd")
    ap.add_argument("--resume", help="plain-text resume (resume_check.py --text-out)")
    ap.add_argument("--out")
    a = ap.parse_args()
    jd = Path(a.jd).read_text(encoding="utf-8", errors="replace")
    res = Path(a.resume).read_text(encoding="utf-8", errors="replace") if a.resume else ""

    # tag each JD line with the importance of the section it sits under
    weight, tagged = "normal", []
    for line in jd.splitlines():
        s = line.strip().strip("*#:-• ").strip()
        if MUST_HEAD.match(s) and len(s) < 60: weight = "must"
        elif NICE_HEAD.match(s) and len(s) < 60: weight = "nice"
        tagged.append((weight, line))

    hits = []
    for names in load_vocab():
        pats = [pattern(n) for n in names]
        n_all, where = 0, set()
        for w, line in tagged:
            c = sum(len(p.findall(line)) for p in pats)
            if c:
                n_all += c
                where.add(w)
        if n_all:
            in_res = any(p.search(res) for p in pats) if res else None
            imp = "must" if "must" in where else ("nice" if where == {"nice"} else "normal")
            hits.append((names, n_all, imp, in_res))
    order = {"must": 0, "normal": 1, "nice": 2}
    hits.sort(key=lambda h: (order[h[2]], -h[1], h[0][0].lower()))

    known = {a.lower() for names in load_vocab() for a in names}
    caps = Counter(m.group(0) for m in re.finditer(r"\b(?:[A-Z][\w.+#/-]*[A-Za-z0-9+#](?:[ \t]+[A-Z][\w.+#/-]*)?)\b", jd))
    def keep(t):
        return len(t) > 2 and t.lower() not in known and t.split()[0] not in STOP

    unknown = [(t, n) for t, n in caps.most_common(40) if keep(t)]

    req = []
    for pat, label in ((r"\d+\s*\+?\s*(?:-\s*\d+\s*)?years?", "experience"), (r"bachelor|master|b\.?tech|degree|graduate", "education"),
                       (r"full[- ]time|part[- ]time|contract|remote|hybrid|on[- ]?site|work from office", "work type"),
                       (r"notice period|immediate joiner|relocat", "joining")):
        for m in re.finditer(r"[^.\n]*(?:" + pat + r")[^.\n]*", jd, re.I):
            req.append((label, m.group(0).strip()[:140]))

    print(f"Known terms in the JD ({len(hits)}):  [importance, JD count, in resume?]")
    for names, n, imp, inr in hits:
        mark = "" if inr is None else ("  yes" if inr else "  NO")
        print(f"  {imp:<6} x{n:<2} {names[0]}{mark}")
    if unknown:
        print("\nOther capitalised phrases (check by hand, add real ones to the keywords file):")
        print("  " + ", ".join(f"{t} (x{n})" for t, n in unknown[:25]))
    if req:
        print("\nHard requirements (cannot be fixed by wording; confirm with the user):")
        for label, s in dict.fromkeys(req):
            print(f"  [{label}] {s}")
    if a.out:
        lines = ["# generated by jd_terms.py: delete what the user has NOT used; keep only confirmed terms"]
        for names, n, imp, _ in hits:
            lines.append("|".join(names) + f"   # {imp}, x{n}")
        Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"\nwrote {a.out}")


if __name__ == "__main__":
    main()
